import PDFDocument from "pdfkit";

export const generatePdf = async (data) => {
    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({
            size: "A4",
            margin: 50,
            info: {
                Author: "MultiAgentX",
                Title: data?.title || "Document",
                Creator: "MultiAgentX"
            }
        });

        const chunks = [];

        doc.on("data", (chunk) => {
            chunks.push(Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk));
        });

        doc.on("end", () => resolve(Buffer.concat(chunks)));
        doc.on("error", (err) => reject(err));

        doc.fontSize(28)
            .text(data?.title || "Document", { align: "center" })
            .fillColor("#111827");

        if (data?.subtitle) {
            doc.moveDown(0.5);
        }

        doc.fontSize(12)
            .text(data?.subtitle || "", { align: "center" })
            .fillColor("#6B7280");

        doc.moveDown(2);

        data?.sections?.forEach((section) => {
            doc.fontSize(18)
                .text(section?.heading || "Section")
                .fillColor("#111827");

            doc.moveDown(0.5);

            section?.points?.forEach((point) => {
                doc.fontSize(12)
                    .text(`• ${point}`, { lineGap: 5 })
                    .fillColor("#374151");
            });

            doc.moveDown();
        });

        doc.moveDown();

        doc.fontSize(10)
            .text("Generated By MultiAgentX", { align: "center" })
            .fillColor("#9CA3AF");

        doc.end();
    });
};